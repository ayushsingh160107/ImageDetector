"""TruthLens AI - Report Generation Service
Generates downloadable JSON and publication-grade PDF forensic analysis reports.
Uses standard Python json library and ReportLab.
"""

from __future__ import annotations

import datetime
import io
import json
import uuid
from typing import Any, Dict, Optional
from PIL import Image

from ml.classifier import PredictionResult
from services.image_service import ImageMetadata

try:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import letter
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.platypus import (
        HRFlowable,
        Image as RLImage,
        KeepTogether,
        Paragraph,
        SimpleDocTemplate,
        Spacer,
        Table,
        TableStyle,
    )
    HAS_REPORTLAB = True
except ImportError:
    HAS_REPORTLAB = False


def generate_json_report(
    prediction: PredictionResult,
    metadata: ImageMetadata,
    region_statistics: Optional[Dict[str, Any]] = None,
    notes: Optional[str] = None,
) -> str:
    """Creates a structured, serializable JSON string of the analysis results."""
    report_data = {
        "report_id": f"TL-{uuid.uuid4().hex[:8].upper()}",
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "application": "TruthLens AI Forensic Suite",
        "version": "1.2.0",
        "image_metadata": {
            "filename": metadata.filename,
            "dimensions": metadata.dimensions_str,
            "format": metadata.format,
            "file_size_kb": metadata.file_size_kb,
            "megapixels": metadata.megapixels,
        },
        "forensic_prediction": {
            "predicted_label": prediction.predicted_label,
            "ai_probability": prediction.ai_probability,
            "real_probability": prediction.real_probability,
            "confidence_score": prediction.confidence_score,
            "raw_logits": prediction.raw_logits,
            "is_inconclusive": prediction.is_inconclusive,
            "threshold_ai": prediction.threshold_ai,
            "threshold_real": prediction.threshold_real,
            "inference_time_ms": prediction.inference_time_ms,
            "uncertainty_warning": prediction.uncertainty_warning,
            "plain_explanation": prediction.plain_explanation,
        },
        "model_specifications": {
            "model_name": prediction.model_name,
            "model_version": prediction.model_version,
            "technical_details": prediction.technical_details,
        },
        "explainability": {
            "region_statistics": region_statistics or {},
        },
        "user_notes": notes or "",
        "forensic_disclaimer": (
            "This report is generated by an automated neural network classifier for educational and "
            "forensic screening purposes. Probabilities are mathematical estimates and should not "
            "be considered absolute legal proof of authenticity or generation."
        ),
    }

    return json.dumps(report_data, indent=2)


def generate_pdf_report(
    prediction: PredictionResult,
    metadata: ImageMetadata,
    thumbnail_image: Optional[Image.Image] = None,
    heatmap_image: Optional[Image.Image] = None,
    notes: Optional[str] = None,
) -> bytes:
    """
    Generates a professional PDF document of the forensic analysis using ReportLab.
    Returns the binary content as bytes.
    """
    if not HAS_REPORTLAB:
        # Fallback to plain text bytes if ReportLab is missing
        text_content = generate_json_report(prediction, metadata, notes=notes)
        return text_content.encode("utf-8")

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()
    primary_color = colors.HexColor("#1e1b4b")  # Deep indigo
    accent_color = colors.HexColor("#4f46e5")   # Bright indigo
    text_dark = colors.HexColor("#0f172a")

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=primary_color,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=14,
        textColor=colors.HexColor("#64748b"),
    )
    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=primary_color,
        spaceBefore=10,
        spaceAfter=6,
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=text_dark,
    )
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8,
        leading=11,
        textColor=colors.HexColor("#475569"),
    )

    story = []

    # Title & Header
    report_id = f"TL-{uuid.uuid4().hex[:8].upper()}"
    timestamp_str = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")

    story.append(Paragraph("TruthLens AI — Forensic Analysis Report", title_style))
    story.append(Paragraph(f"Report ID: {report_id}  |  Generated: {timestamp_str}  |  Engine: {prediction.model_name}", subtitle_style))
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=1.5, color=accent_color, spaceBefore=4, spaceAfter=12))

    # Executive Summary Card
    label_color = "#dc2626" if "AI" in prediction.predicted_label else ("#16a34a" if "Real" in prediction.predicted_label else "#d97706")
    summary_html = f"""
    <b>Classification Result:</b> <font color="{label_color}"><b>{prediction.predicted_label.upper()}</b></font><br/>
    <b>Estimated AI Probability:</b> {prediction.ai_probability * 100:.1f}% &nbsp;&nbsp;|&nbsp;&nbsp;
    <b>Authentic Camera Probability:</b> {prediction.real_probability * 100:.1f}% &nbsp;&nbsp;|&nbsp;&nbsp;
    <b>Confidence:</b> {prediction.confidence_score * 100:.1f}%
    """
    story.append(Paragraph(summary_html, body_style))
    story.append(Spacer(1, 8))

    # Plain Language Explanation
    story.append(Paragraph("<b>Forensic Summary:</b> " + prediction.plain_explanation, body_style))
    if prediction.uncertainty_warning:
        story.append(Spacer(1, 4))
        story.append(Paragraph(f"<b>Uncertainty Flag:</b> <font color='#b45309'>{prediction.uncertainty_warning}</font>", body_style))
    story.append(Spacer(1, 12))

    # Image Details Table
    story.append(Paragraph("Inspected Asset Metadata", section_heading))
    meta_table_data = [
        [Paragraph("<b>Filename</b>", body_style), Paragraph(metadata.filename, body_style)],
        [Paragraph("<b>Dimensions</b>", body_style), Paragraph(metadata.dimensions_str, body_style)],
        [Paragraph("<b>File Size</b>", body_style), Paragraph(f"{metadata.file_size_kb:.1f} KB", body_style)],
        [Paragraph("<b>Format / Mode</b>", body_style), Paragraph(f"{metadata.format} ({metadata.mode})", body_style)],
        [Paragraph("<b>Inference Latency</b>", body_style), Paragraph(f"{prediction.inference_time_ms:.1f} ms", body_style)],
    ]
    meta_table = Table(meta_table_data, colWidths=[140, 380])
    meta_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 14))

    # Evidence & Metrics Table
    story.append(Paragraph("Forensic Model Scores & Decision Bounds", section_heading))
    scores_table_data = [
        [Paragraph("<b>Metric</b>", body_style), Paragraph("<b>Value</b>", body_style), Paragraph("<b>Specification</b>", body_style)],
        [Paragraph("AI-Generated Score", body_style), Paragraph(f"{prediction.ai_probability * 100:.2f}%", body_style), Paragraph(f"Threshold >= {prediction.threshold_ai * 100:.0f}%", body_style)],
        [Paragraph("Camera-Captured Score", body_style), Paragraph(f"{prediction.real_probability * 100:.2f}%", body_style), Paragraph(f"Threshold <= {prediction.threshold_real * 100:.0f}%", body_style)],
        [Paragraph("Decision State", body_style), Paragraph("Inconclusive" if prediction.is_inconclusive else "Decisive", body_style), Paragraph("Uncertainty boundary evaluation", body_style)],
        [Paragraph("Raw Logits [Real, AI]", body_style), Paragraph(str(prediction.raw_logits), body_style), Paragraph("Unnormalized neural head output", body_style)],
    ]
    scores_table = Table(scores_table_data, colWidths=[160, 140, 220])
    scores_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#ede9fe")),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("PADDING", (0, 0), (-1, -1), 5),
    ]))
    story.append(scores_table)
    story.append(Spacer(1, 14))

    # Optional Notes
    if notes:
        story.append(Paragraph("Examiner Notes", section_heading))
        story.append(Paragraph(notes, body_style))
        story.append(Spacer(1, 10))

    # Disclaimer Footer
    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", thickness=0.8, color=colors.HexColor("#94a3b8"), spaceBefore=8, spaceAfter=8))
    disclaimer_text = (
        "<b>Important Notice:</b> TruthLens AI provides mathematical forensic approximations based on deep learning "
        "feature analysis. Predictions do not constitute absolute legal certainty or definitive proof. "
        "Adversarial perturbations, social media recompression, and novel generative architectures may influence output scores."
    )
    story.append(Paragraph(disclaimer_text, disclaimer_style))

    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()
